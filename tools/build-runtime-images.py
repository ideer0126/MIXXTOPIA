#!/usr/bin/env python3
"""Export runtime WebP derivatives; originals remain the editable art source.
Requires Pillow with libwebp: python -m pip install Pillow
"""
from pathlib import Path
from PIL import Image
import json

repo = Path(__file__).resolve().parent.parent
output = repo / 'assets/runtime'
manifest = {}
for source in sorted((repo / 'assets').rglob('*.webp')):
    if output in source.parents:
        continue
    relative = source.relative_to(repo)
    target = output / source.relative_to(repo / 'assets')
    with Image.open(source) as image:
        name = source.name
        limit = 768
        sampling = Image.Resampling.NEAREST
        if name == 'strange-muse-cover.webp':
            limit = 128
            sampling = Image.Resampling.LANCZOS
        elif name.startswith('birthday-hall-'):
            limit = 1920  # 40x28 room in the existing three-times detail buffer.
        elif name in ('p0-bedroom.webp', 'rings-booth-v1.webp'):
            limit = 960
        elif name == 'muse-portraits-v1.webp':
            limit = 384  # 128px per avatar cell; CSS uses normalized atlas coordinates.
        factor = min(1, limit / max(image.size))
        size = tuple(max(1, round(value * factor)) for value in image.size)
        result = image.resize(size, sampling) if size != image.size else image.copy()
        target.parent.mkdir(parents=True, exist_ok=True)
        options = {'icc_profile': image.info['icc_profile']} if 'icc_profile' in image.info else {}
        result.save(target, 'WEBP', lossless=True, exact=True, method=6, **options)
        manifest[relative.as_posix()] = {
            'src': target.relative_to(repo).as_posix(),
            'width': image.width, 'height': image.height,
            'runtimeWidth': size[0], 'runtimeHeight': size[1],
        }
        print(f'{relative}: {image.size} -> {size}, {source.stat().st_size} -> {target.stat().st_size}', flush=True)
(output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
(repo / 'js/runtime-images.js').write_text(
    '// Generated by tools/build-runtime-images.py; source coordinates remain unchanged.\n'
    "(function (root) { 'use strict'; root.MIXX_RUNTIME_IMAGES = " + json.dumps(manifest, separators=(',', ':')) +
    "; })(typeof window !== 'undefined' ? window : globalThis);\n")
print('TOTAL', sum((repo / src).stat().st_size for src in manifest),
      '->', sum((repo / item['src']).stat().st_size for item in manifest.values()))
